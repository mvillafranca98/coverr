#!/usr/bin/env node
/**
 * Generates `seed/demo.sql`: a fabricated band used for the product shots on
 * the landing page, and for nothing else.
 *
 * It exists because the alternative was publishing screenshots of Jungla —
 * a real band's real takings, with real buyers' names in the orders list.
 * Everything below is invented: the band, the venue, every buyer, every
 * figure. The landing page says so next to the images.
 *
 * Deterministic on purpose. A fixed seed means re-running this reproduces the
 * same numbers, so a screenshot can be retaken months later and still match
 * the one beside it.
 *
 *   node seed/make-demo.mjs
 *   npx wrangler d1 execute coverr-db --local --file=./seed/demo.sql
 */
import { writeFileSync } from "node:fs";

/** Mulberry32 — small, seeded, and good enough to pick names with. */
function rng(seed) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
