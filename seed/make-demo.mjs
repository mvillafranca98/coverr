const fullName = () => `${pick(FIRST)} ${pick(LAST)}`;

const esc = (s) => String(s).replace(/'/g, "''");
const CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";
const token = (n) => Array.from({ length: n }, () => CROCKFORD[Math.floor(rand() * 32)]).join("");

const BAND = "bnd_demo";
const EVENT = "evt_demo";
const STAFF_TOKEN = "demostaff00000000000000000000000";

const PRESALE = 20000; // L200
const DOOR = 25000; // L250

/**
 * The shape of a real night, not a flattering one: presale is the biggest
 * slice, cash at the door is a third of the gate (39% in the baseline event),
 * and a handful of people never turn up.
 */
const CHANNELS = [
  { channel: "online", rule: "pr_demo_presale", amount: PRESALE, orders: 38, maxQty: 3 },
  { channel: "door_online", rule: "pr_demo_door", amount: DOOR, orders: 22, maxQty: 2 },
  { channel: "door_cash", rule: "pr_demo_door", amount: DOOR, orders: 24, maxQty: 2 },
  { channel: "comp", rule: null, amount: 0, orders: 5, maxQty: 1 },
];

const lines = [];
const out = (s) => lines.push(s);

out("-- GENERATED by seed/make-demo.mjs — do not edit by hand.");
out("-- A fabricated band for the landing page's product shots. No real person,");
out("-- band, venue or figure appears here. Re-run the generator to change it.");
out("");
out(`DELETE FROM bands WHERE id = '${BAND}';`);
out("");
out(
  `INSERT INTO bands (id, name, slug, contact_email, created_at) VALUES ` +
    `('${BAND}', 'Ruido Local', 'ruido-local', 'demo@ejemplo.com', '2026-09-01T00:00:00Z');`,
);
out("");
out("INSERT INTO band_members (id, band_id, name, split_pct, is_core, sort_order) VALUES");
out(
  `${[
    ["mem_demo_1", "Keyla", 28],
    ["mem_demo_2", "Marvin", 28],
    ["mem_demo_3", "Josué", 24],
    ["mem_demo_4", "Elder", 20],
  ]
    .map(([id, name, pct], i) => `  ('${id}', '${BAND}', '${name}', ${pct}, 1, ${i})`)
    .join(",\n")};`,
);
out("");
out(
  `INSERT INTO bank_accounts (id, band_id, bank, account_number, holder_name, is_default, active, sort_order) VALUES\n` +
    `  ('acc_demo_bac', '${BAND}', 'BAC', '000000000', 'NOMBRE DEL TITULAR', 1, 1, 0);`,
);
out("");
out(`INSERT INTO events (
  id, band_id, name, slug, venue, starts_at, doors_at, description, music_type,
  thank_you_note, capacity_cap, refund_policy, refund_policy_text,
  wristbands_start, staff_token, status, created_at
) VALUES (
  '${EVENT}', '${BAND}', 'Noche de Ruido', 'noche-de-ruido',
  'Casa Quinchón', '2026-10-24T21:00:00-06:00', '2026-10-24T20:00:00-06:00',
  'Tres bandas, una noche. Barra abierta hasta las 9pm.',
  'Rock / punk',
  '¡Gracias! Guardá tu código QR — lo necesitás en la entrada.',
  220, '24h',
  'Podés solicitar reembolso dentro de las 24 horas siguientes a tu compra.',
  200, '${STAFF_TOKEN}', 'live', '2026-09-20T00:00:00Z'
);`);
out("");
out(
  "INSERT INTO price_rules (id, event_id, label, amount, max_qty, starts_at, ends_at, activates_on_selloff_of, sort_order) VALUES\n" +
    `  ('pr_demo_presale', '${EVENT}', 'Preventa', ${PRESALE}, 120, NULL, '2026-10-24T20:00:00-06:00', NULL, 0),\n` +
    `  ('pr_demo_door', '${EVENT}', 'Puerta', ${DOOR}, NULL, '2026-10-24T20:00:00-06:00', NULL, 'pr_demo_presale', 1);`,
);
out("");

const orderRows = [];
const attendeeRows = [];
let n = 0;
let people = 0;
let checkedIn = 0;

for (const spec of CHANNELS) {
  for (let i = 0; i < spec.orders; i++) {
    n += 1;
    const id = `ord_demo_${String(n).padStart(3, "0")}`;
    const qty = spec.channel === "comp" ? 1 : 1 + Math.floor(rand() * spec.maxQty);
    const buyer = fullName();
    const email = `${buyer.toLowerCase().replace(/[^a-z]/g, ".")}@ejemplo.com`;
    const hour = 18 + Math.floor(rand() * 4);
    const createdAt =
      spec.channel === "online"
        ? `2026-10-${String(10 + Math.floor(rand() * 13)).padStart(2, "0")}T${hour}:${String(Math.floor(rand() * 60)).padStart(2, "0")}:00Z`
        : `2026-10-25T0${Math.floor(rand() * 3)}:${String(Math.floor(rand() * 60)).padStart(2, "0")}:00Z`;

    orderRows.push(
      `  ('${id}', '${EVENT}', '${token(6)}', '${esc(buyer)}', '${esc(email)}', ` +
        `'${98000000 + Math.floor(rand() * 1999999)}', ${qty}, ` +
        `${spec.rule ? `'${spec.rule}'` : "NULL"}, ${spec.amount * qty}, '${spec.channel}', ` +
        `'confirmed', '${spec.channel === "door_cash" || spec.channel === "comp" ? "n/a" : "matched"}', ` +
        `${spec.channel === "comp" ? "NULL" : "'BAC'"}, '24h', '${createdAt}')`,
    );

    for (let a = 0; a < qty; a++) {
      people += 1;
      // A real door leaves people outside: some presale buyers never show.
      const shows = spec.channel === "online" ? rand() > 0.12 : true;
      if (shows) checkedIn += 1;
      const at = shows
        ? `'2026-10-25T0${Math.floor(rand() * 3)}:${String(Math.floor(rand() * 60)).padStart(2, "0")}:00Z'`
        : "NULL";
      attendeeRows.push(
        `  ('att_demo_${String(people).padStart(3, "0")}', '${id}', '${esc(a === 0 ? buyer : fullName())}', ` +
          `NULL, '${token(22)}', ${at}, ${shows ? "'Puerta'" : "NULL"}, ${shows ? "'demo'" : "NULL"})`,
      );
    }
  }
}

out(
  "INSERT INTO orders (id, event_id, short_code, payer_name, payer_email, payer_phone, quantity,\n" +
    "  price_rule_id, expected_amount, channel, status, verification_status, bank_selected,\n" +
    "  refund_policy, created_at) VALUES",
);
out(`${orderRows.join(",\n")};`);
out("");
out(
  "INSERT INTO attendees (id, order_id, name, note, qr_token, checked_in_at, checked_in_by, checked_in_device) VALUES",
);
out(`${attendeeRows.join(",\n")};`);
out("");
out("INSERT INTO expenses (id, event_id, label, category, amount, paid, created_at) VALUES");
out(
  `${[
    ["exp_demo_1", "Sonido", "sonido", 450000],
    ["exp_demo_2", "Arte y flyer", "arte", 120000],
    ["exp_demo_3", "Fotografía", "fotos", 100000],
    ["exp_demo_4", "Local", "local", 200000],
  ]
    .map(
      ([id, label, cat, amt]) =>
        `  ('${id}', '${EVENT}', '${label}', '${cat}', ${amt}, 1, '2026-10-20T00:00:00Z')`,
    )
    .join(",\n")};`,
);

writeFileSync("seed/demo.sql", `${lines.join("\n")}\n`, "utf8");

